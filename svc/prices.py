# 月額制（サブスク型）との総額比較
#
# 金額は各社が公開しているページの表示値。2026年9月時点で実際に読んで写した。
# 「36か月」を横軸に置くのは、月額制の各社が“譲渡”や“契約満了”の区切りに
# その付近を置いていることが多いため。こちらの都合で選んだ区切りではない。
#
# ここに他社名は書かない。サイト上でも書かない。
# 比べるのは「仕組み」であって、特定の会社を名指しで叩く商売はしない。
# ══════════════════════════════════════════════════════════════════
