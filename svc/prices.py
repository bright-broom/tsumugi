def subs_total(m, months=COMPARE_MONTHS):
    """月額制の総額。初期費用＋月額×か月"""
    return m["init"] + m["monthly"] * months


def ours_total(build_price, run_key, months=COMPARE_MONTHS):
    """当方の総額。買い切り＋運用×か月（運用は途中でやめられる）"""
    run = next(r for r in RUN if r["key"] == run_key)["price"]
    return build_price + run * months


def compare_rows(months=COMPARE_MONTHS):
    """ページ数の近いものどうしを並べる。当方が高い行も、そのまま出す。"""
    pairs = [
        (SUBS_MARKET[0], SINGLE["price"], "run_light", SINGLE["name"], SINGLE["pages"]),
        (SUBS_MARKET[1], BUILD[0]["price"], "run_basic", BUILD[0]["name"], BUILD[0]["pages"]),
        (SUBS_MARKET[2], BUILD[1]["price"], "run_standard", BUILD[1]["name"], BUILD[1]["pages"]),
    ]
    out = []
    for sub, price, run_key, name, pages in pairs:
        st = subs_total(sub, months)
        ot = ours_total(price, run_key, months)
        out.append({
            "sub_name": sub["name"], "sub_pages": sub["pages"],
            "sub_monthly": sub["monthly"], "sub_total": st,
            "our_name": name, "our_pages": pages, "our_price": price,
            "our_run": next(r for r in RUN if r["key"] == run_key)["price"],
            "our_total": ot, "diff": ot - st,
        })
    return out


