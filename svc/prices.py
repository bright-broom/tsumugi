def subsidy_calc():
    items = SUBSIDY["package"]
    total = sum(a for _, _, a in items)
    web = sum(a for k, _, a in items if k == "ウェブサイト関連費")
    pr = sum(a for k, _, a in items if k == "広報費")
    web_sub = min(int(web * 2 / 3), SUBSIDY["web_cap"])
    pr_sub = int(pr * 2 / 3)
    grant = min(web_sub + pr_sub, SUBSIDY["cap"])
    return {
        "total": total, "web": web, "pr": pr,
        "web_sub": web_sub, "pr_sub": grant - web_sub,
        "grant": grant, "net": total - grant,
    }


